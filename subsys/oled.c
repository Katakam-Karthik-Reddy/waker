void setup_oled_display(void){
    __disable_irq();
    setup_OLED_pins();

    send_cmd_oled(SET_DISPLAY_OFF, 0, NULL);
    send_cmd_oled(SET_MULTIPLEX_RATIO, 1, (uint8_t[]){MULTIPLEX_32});
    send_cmd_oled(SET_MEMORY_ADDRESSING_MODE, 1, (uint8_t[]){HORIZONTAL_ADDRESSING_MODE});
    send_cmd_oled(SET_DISPLAY_START_LINE, 0, NULL);
    send_cmd_oled(SET_DISPLAY_OFFSET, 1, (uint8_t[]){0x00U});
    send_cmd_oled(SET_SEGMENT_RE_MAP_SEG0, 0, NULL);
    send_cmd_oled(SET_COM_OUTPUT_SCAN_DIRECTION_NORMAL_MODE, 0, NULL);
    send_cmd_oled(SET_COM_PINS_HARDWARE_CONFIGURATION, 1, (uint8_t[]){SEQUENTIAL_COM_PIN_CONFIGURATION});
    send_cmd_oled(SET_CONTRAST_CONTROL, 1, (uint8_t[]){CONTRAST_RESET_VALUE});
    send_cmd_oled(ENTIRE_DISPLAY_ON_RESUME_TO_RAM, 0, NULL);
    send_cmd_oled(SET_NORMAL_MODE, 0, NULL);
    send_cmd_oled(SET_DISPLAY_CLOCK_DIVIDE_RATIO_OSCILLATIOR_FREQUENCY, 1, (uint8_t[]){CLOCK_DIVIDE_RATIO_OSCILLATOR_FREQUENCY_RESET_VALUE});
    send_cmd_oled(SET_PRE_CHARGE_PERIOD, 1, (uint8_t[]){PRE_CHARGE_PERIOD_RESET_VALUE});
    send_cmd_oled(CHARGE_PUMP_SETTING, 1, (uint8_t[]){CHARGE_PUMP_ENABLE});
    send_cmd_oled(DEACTIVATE_SCROLL, 0, NULL);
    send_cmd_oled(SET_COLUMN_ADDRESS, 2, (uint8_t[]){COLUMN_ADDRESS_START_RESET_VALUE, COLUMN_ADDRESS_END_RESET_VALUE});
    send_cmd_oled(SET_PAGE_ADDRESS, 2, (uint8_t[]){PAGE_ADDRESS_START_RESET_VALUE, PAGE_ADDRESS_END_RESET_VALUE});
    send_cmd_oled(SET_DISPLAY_ON, 0, NULL);
    
    __enable_irq();
}

void send_cmd_oled(uint8_t cmd, uint8_t leng, uint8_t *args){
    start_I2C1_transmit();
    send_I2C1_data(COMMAND_STREAM);
    send_I2C1_data(cmd);

    for(size_t arg_i=0; arg_i < leng; arg_i++){
        send_I2C1_data(args[arg_i]);
    }
    stop_I2C1_transmit();
}

void send_data_oled(uint8_t *data, size_t leng){
    start_I2C1_transmit();
    send_I2C1_data(DATA_STREAM);
    
    for(size_t data_index=0; data_index < leng; data_index++){
        send_I2C1_data(data[data_index]);
    }
    stop_I2C1_transmit();
}


